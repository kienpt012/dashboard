/** Tên biểu tượng người dùng chọn được (ô chọn biểu tượng). */
export const ICON_NAMES = [...Object.keys(ICONS), 'jarvis'];

export function DeskIcon({ name, color, size }: { name: string; color?: string | null; size?: number }) {
  if (name === 'jarvis') return <JarvisMark size={size ?? 16} />;
  const Icon = ICONS[name] ?? LinkOutlined;
  return <Icon style={{ color: color ?? undefined, fontSize: size }} />;
}

/** Màu ổn định sinh từ một chuỗi (tên miền, tên lối tắt) cho ô biểu tượng không có màu riêng. */
export function hashColor(text: string) {
  const palette = ['#2563eb', '#0891b2', '#059669', '#65a30d', '#d97706', '#dc2626', '#db2777', '#7c3aed', '#4f46e5', '#0d9488'];
  let hash = 0;
  for (const char of text) hash = (hash * 31 + char.charCodeAt(0)) | 0;
  return palette[Math.abs(hash) % palette.length];
}

